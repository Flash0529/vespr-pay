// Generates agents/src/codemap.js (ES module) from extensions/murmio-collab/lib/codemap.js (the source of truth, CommonJS).
// The agent image only contains agents/, so it needs its own copy. A test (extensions/murmio-collab/test/codemap.test.js) fails if they drift.
//   node scripts/sync-codemap.mjs
import fs from 'node:fs'
import path from 'node:path'
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
export function generate () {
  const src = fs.readFileSync(path.join(root, 'extensions/murmio-collab/lib/codemap.js'), 'utf8')
  const m = /^module\.exports = \{([^}]*)\}\s*$/m.exec(src)
  if (!m) throw new Error('module.exports line not found in codemap.js')
  return '// GENERATED from extensions/murmio-collab/lib/codemap.js by scripts/sync-codemap.mjs: do not edit this file, edit the source and run the script.\n' + src.replace(m[0], `export {${m[1]}}`).replace(/^'use strict'\n/, '')
}
if (process.argv[1] === new URL(import.meta.url).pathname) { fs.writeFileSync(path.join(root, 'agents/src/codemap.js'), generate()); console.log('wrote agents/src/codemap.js') }
